/**
 * 把后端信号标记名解析成词典键。
 *
 * 后端标记 text = `{emoji} {name}`(如「⚠️ BOLL 收口」「⚠️ 诱多 2 类」),
 * 这里去掉 emoji;「诱多/诱空」带数量后缀,按前缀回退到基础词条。
 *
 * 找不到就返回 null —— 调用方只显示「暂无解释」,不猜、不编。
 */
export function resolveSignalTerm(name: string): string | null {
  if (GLOSSARY[name]) return name;
  if (name.startsWith('诱多')) return '诱多';
  if (name.startsWith('诱空')) return '诱空';
  if (name.startsWith('BOLL 收口')) return 'BOLL 收口';
  if (name.startsWith('BOLL 触上轨')) return 'BOLL 触上轨';
  if (name.startsWith('BOLL 触下轨')) return 'BOLL 触下轨';
  if (name.startsWith('MACD 金叉')) return 'MACD 金叉';
  if (name.startsWith('MACD 死叉')) return 'MACD 死叉';
  if (name.startsWith('KDJ 金叉')) return 'KDJ 金叉';
  if (name.startsWith('KDJ 死叉')) return 'KDJ 死叉';
  return null;
}